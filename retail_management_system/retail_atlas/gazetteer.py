def normalise(text):
    """Upper-case, strip accents/glottal stops, and collapse punctuation to spaces."""
    text = unicodedata.normalize('NFKD', text or '')
    text = ''.join(c for c in text if not unicodedata.combining(c))
    text = re.sub(r"['’ʻ`]", '', text.upper())
    text = re.sub(r'[^A-Z0-9]+', ' ', text)
    return text.strip()


def locate(address):
    """Return (lat, lng) for the best village match in `address`, or None.

    Tries every contiguous run of words, longest first and left to right, so
    "MATAUTU FALEALILI" hits its own entry before falling back to "MATAUTU".
    """
    words = normalise(address).split()
    for size in range(len(words), 0, -1):
        for start in range(len(words) - size + 1):
            hit = VILLAGES.get(' '.join(words[start:start + size]))
            if hit:
                return hit
    return None
